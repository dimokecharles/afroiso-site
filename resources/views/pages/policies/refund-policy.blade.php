<p>This policy explains when {{ config('afroiso.name') }} ("AfroISO", "we") refunds fees paid for training courses and publications, and how to ask for a refund.</p>
<p><span class="confirm">To confirm: every period and percentage in this policy is a proposal for AfroISO to approve or change.</span></p>

<h2>1. Training courses</h2>
<h3>If you cancel</h3>
<ul>
    <li><strong><span class="confirm">7 days or more</span> before the course start date:</strong> we refund the full course fee.</li>
    <li><strong>Fewer than <span class="confirm">7 days</span> before the start date:</strong> you can move to the next intake of the same course at no extra cost, or receive a refund of <span class="confirm">50%</span> of the course fee.</li>
    <li><strong>After the course has started, or after you have been given access to the course material:</strong> the fee is not refundable. You may transfer <span class="confirm">once</span> to a later intake of the same course if you ask within <span class="confirm">14 days</span> of the start date.</li>
</ul>
<h3>Changing the person attending</h3>
<p>You may give your place to another person before the course starts, at no extra cost. Tell us the new person's name and contact details in writing.</p>
<h3>If we cancel or postpone</h3>
<p>If we cancel a course, or move its start date and the new date does not suit you, you can choose a full refund or a transfer to another intake.</p>
<h3>Certificates</h3>
<p>The course fee pays for the training. No refund is due because a participant did not complete the course or did not pass an assessment.</p>

<h2>2. Books and magazines</h2>
<ul>
    <li><strong>Digital publications:</strong> once a digital book or magazine has been delivered to you it cannot be returned, so it is not refundable. If the file is faulty or you received the wrong publication, tell us and we will replace it or refund you.</li>
    <li><strong>Printed publications:</strong> if a printed publication arrives damaged, or is not the one you ordered, tell us within <span class="confirm">7 days</span> of delivery and we will replace it or refund you.</li>
</ul>

<h2>3. Consulting services</h2>
<p>Refunds and cancellations for consulting work are set out in the written agreement for each engagement.</p>

<h2>4. How to ask for a refund</h2>
<ol>
    <li>Email <a href="mailto:{{ config('afroiso.email') }}">{{ config('afroiso.email') }}</a> with your name, your invoice number and the reason for your request.</li>
    <li>We will confirm that we have received your request and tell you whether it is approved.</li>
    <li>Approved refunds are paid within <span class="confirm">14 working days</span>, using the same method you used to pay.</li>
</ol>
<p>Bank and transfer charges are outside our control. <span class="confirm">Any charges made by the bank or payment provider are deducted from the refund (to confirm).</span> Refunds are paid in the currency of the original payment.</p>

<h2>5. Your legal rights</h2>
<p>This policy does not take away any right you have under consumer protection law.</p>

