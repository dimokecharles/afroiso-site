<h2>2. Information we collect</h2>
<ul>
    <li><strong>Enquiries and orders.</strong> When you send the contact form we collect your name, email address, the message you write, and your phone number and organisation if you give them.</li>
    <li><strong>Enrolment and invoicing.</strong> When you enrol on a course or order a publication, our office collects the details needed to invoice you and deliver the service, such as your name, contact details, the course or publication chosen and your payment records.</li>
    <li><strong>Certificates.</strong> For each certificate we issue we keep the certificate number, the holder's name, the course and the date of issue.</li>
    <li><strong>Technical information.</strong> Our hosting provider records standard server logs, such as your IP address, browser type, the pages requested and the time of each request.</li>
    <li><strong>Visit counts.</strong> We count how many times each page is visited and which website a visitor came from. We do this without cookies and without storing your IP address, so the counts cannot identify you.</li>
</ul>
<p>We do not ask for card details on this website. Invoices are paid using the payment details our office sends you.</p>

<h2>3. How we use your information</h2>
<ul>
    <li>To reply to your enquiry and send you the dates, fees and next steps you asked for.</li>
    <li>To enrol you, invoice you, deliver your course or publication and issue your certificate.</li>
    <li>To let anyone who has a certificate number confirm that the certificate is genuine.</li>
    <li>To keep the website secure and working properly.</li>
    <li>To meet our legal, tax and accounting duties.</li>
</ul>
<p>We use your information because you asked us for something, because we need it to perform our agreement with you, because the law requires it, or because you gave your consent. We do not sell personal information, and we do not use it for marketing unless you have agreed to that.</p>

<h2>4. Certificate verification</h2>
<p>Anyone who enters a valid certificate number on our Verify page is shown the name of the certificate holder, the course and the date of issue. This lets employers and auditors confirm a certificate. If you hold an AfroISO certificate and have a concern about this, contact us.</p>

