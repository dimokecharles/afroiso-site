    <li><strong>Google Maps</strong>, on the Contact page.</li>
    <li><strong>Google Fonts and Font Awesome</strong>, which supply the fonts and icons used on every page.</li>
    <li><strong>WhatsApp</strong>, only when you press a WhatsApp button. Your chat with us then takes place in WhatsApp, under WhatsApp's own privacy policy.</li>
